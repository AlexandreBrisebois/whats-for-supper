#!/usr/bin/env python3
"""Generate or verify the compact codebase cross-reference index (docs/generated/route-map.md)."""

from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys

import yaml

ROOT = Path(__file__).resolve().parents[2]
OUTPUT_REL = Path("docs/generated/route-map.md")
MARKER = "<!-- Generated by `task agent:map` (`scripts/agent/route_map.py`). Do not edit manually. -->"


def format_table(headers: list[str], rows: list[list[str]]) -> list[str]:
    escaped = [[cell.replace("|", "\\|") for cell in row] for row in rows]
    widths = [
        max(3, len(h), *(len(r[i]) for r in escaped)) if escaped else max(3, len(h))
        for i, h in enumerate(headers)
    ]
    head = "| " + " | ".join(h.ljust(w) for h, w in zip(headers, widths)) + " |"
    sep = "| " + " | ".join("-" * w for w in widths) + " |"
    body = ["| " + " | ".join(c.ljust(w) for c, w in zip(r, widths)) + " |" for r in escaped]
    return [head, sep, *body]


def collect_pwa_routes(root: Path) -> list[list[str]]:
    app_dir = root / "pwa/src/app"
    if not app_dir.is_dir():
        return []
    entries: list[tuple[str, list[str]]] = []
    for page in sorted(app_dir.rglob("page.tsx")):
        rel_parts = [
            p for p in page.relative_to(app_dir).parent.parts if not (p.startswith("(") and p.endswith(")"))
        ]
        route = "/" + "/".join(rel_parts)
        text = page.read_text(encoding="utf-8")
        stores = sorted(set(re.findall(r"from ['\"]@/store/([\w-]+)['\"]", text)))
        apis = sorted(set(re.findall(r"from ['\"]@/lib/api/([\w-]+)['\"]", text)) - {"generated"})
        comps = sorted(set(re.findall(r"from ['\"]@/components/(?:[\w-]+/)?([\w-]+)['\"]", text)))
        refs = [*(f"`{s}`" for s in stores), *(f"`api/{a}`" for a in apis)]
        if not refs and comps:
            refs = [f"`{c}`" for c in comps[:2]]
        elif comps:
            refs.append(f"`{comps[0]}`")
        rel_page = page.relative_to(root).as_posix()
        entries.append((route, [f"`{route}`", f"`{rel_page}`", ", ".join(refs) or "—"]))
    entries.sort(key=lambda item: (item[0] != "/", item[0], item[1][1]))
    return [row for _, row in entries]


def collect_pwa_stores(root: Path) -> list[list[str]]:
    store_dir = root / "pwa/src/store"
    if not store_dir.is_dir():
        return []
    rows: list[list[str]] = []
    for path in sorted(store_dir.glob("*.ts")):
        if path.name.endswith(".test.ts") or path.name == "index.ts":
            continue
        text = path.read_text(encoding="utf-8")
        hooks = sorted(set(re.findall(r"export const (use\w+)", text)))
        apis = sorted(set(re.findall(r"from ['\"]@/lib/api/([\w-]+)['\"]", text)) - {"generated"})
        rows.append([
            f"`{path.name}`",
            ", ".join(f"`{h}`" for h in hooks) or "state helper",
            ", ".join(f"`{a}.ts`" for a in apis) or "client-local",
        ])
    return rows


def collect_api_wrappers(root: Path) -> list[list[str]]:
    api_dir = root / "pwa/src/lib/api"
    if not api_dir.is_dir():
        return []
    rows: list[list[str]] = []
    for path in sorted(api_dir.glob("*.ts")):
        if path.name.endswith(".test.ts"):
            continue
        text = path.read_text(encoding="utf-8")
        kiota = sorted(set(re.findall(r"apiClient\.api\.(\w+)", text)))
        if kiota:
            target = ", ".join(f"`api.{k}`" for k in kiota)
        elif "fetch(" in text:
            target = "Direct `fetch` / SSR transport"
        elif "Kiota" in text or "RequestAdapter" in text:
            target = "Kiota client factory"
        else:
            target = "Wire mapper / pure helper"
        rows.append([f"`pwa/src/lib/api/{path.name}`", target])
    return rows


def collect_controllers(root: Path) -> list[list[str]]:
    ctrl_dir = root / "api/src/RecipeApi/Controllers"
    if not ctrl_dir.is_dir():
        return []
    rows: list[list[str]] = []
    for path in sorted(ctrl_dir.glob("*Controller.cs")):
        text = path.read_text(encoding="utf-8")
        ctrl_stem = path.stem.removesuffix("Controller").lower()
        route_match = re.search(r'\[Route\("([^"]+)"\)\]', text)
        prefix = "/" + (route_match.group(1).replace("[controller]", ctrl_stem).lstrip("/") if route_match else "")
        verbs = re.findall(r"\[Http(Get|Post|Put|Delete|Patch)", text)
        verb_summary = f"{len(verbs)} ({'/'.join(sorted({v.upper() for v in verbs}))})" if verbs else "0"
        ctor_match = re.search(rf"class\s+{re.escape(path.stem)}\s*\(([^)]*)\)", text, re.DOTALL)
        if not ctor_match:
            ctor_match = re.search(rf"public\s+{re.escape(path.stem)}\s*\(([^)]*)\)", text, re.DOTALL)
        deps: list[str] = []
        if ctor_match:
            for raw_param in ctor_match.group(1).split(","):
                tokens = re.sub(r"\[[^\]]+\]", "", raw_param).strip().split()
                if len(tokens) >= 2:
                    dep_type = re.sub(r"<.*>", "", tokens[-2]).rstrip("?")
                    if dep_type not in {"ILogger", "IConfiguration", "CancellationToken"}:
                        deps.append(f"`{dep_type}`")
        rows.append([f"`{path.stem}`", f"`{prefix}`", verb_summary, ", ".join(deps[:4]) or "—"])
    return rows


def collect_service_groups(root: Path) -> list[list[str]]:
    api_root = root / "api/src/RecipeApi"
    if not api_root.is_dir():
        return []
    candidate_dirs = [
        api_root / "Services",
        *(sorted(p for p in (api_root / "Services").iterdir() if p.is_dir()) if (api_root / "Services").is_dir() else []),
        api_root / "Management",
        api_root / "Recipes",
    ]
    rows: list[list[str]] = []
    seen: set[Path] = set()
    for folder in candidate_dirs:
        if not folder.is_dir() or folder in seen:
            continue
        seen.add(folder)
        cs_files = sorted(folder.glob("*.cs"))
        if not cs_files:
            continue
        stems = sorted({f.name.split(".")[0] for f in cs_files})
        preview = ", ".join(f"`{s}`" for s in stems[:5])
        if len(stems) > 5:
            preview += f" (+{len(stems) - 5} more)"
        rows.append([f"`{folder.relative_to(root).as_posix()}`", str(len(stems)), preview])
    return rows


def collect_workflows(root: Path) -> list[list[str]]:
    wf_dir = root / "api/src/RecipeApi/Workflows"
    if not wf_dir.is_dir():
        return []
    rows: list[list[str]] = []
    for path in sorted(wf_dir.glob("*.yaml")):
        data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        name = data.get("name", path.stem)
        params = [str(p) for p in (data.get("parameters") or [])]
        processors: list[str] = []
        for task in data.get("tasks") or []:
            proc = task.get("processor")
            if proc and proc not in processors:
                processors.append(str(proc))
        rows.append([
            f"`{name}`",
            ", ".join(f"`{p}`" for p in params) or "—",
            " → ".join(f"`{p}`" for p in processors) or "—",
        ])
    return rows


def collect_sql_objects(root: Path) -> list[list[str]]:
    schema_path = root / "api/database/schema.sql"
    if not schema_path.is_file():
        return []
    text = schema_path.read_text(encoding="utf-8")
    rows: list[list[str]] = []
    table_rx = re.compile(
        r"CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?(\w+)\s*\((.*?)\);\s*$",
        re.MULTILINE | re.DOTALL,
    )
    for match in table_rx.finditer(text):
        name, body = match.group(1), match.group(2)
        refs = sorted(set(re.findall(r"REFERENCES\s+(\w+)\s*\(", body)))
        rows.append([f"`{name}`", "table", ", ".join(f"`{r}`" for r in refs) or "root"])
    for view in re.findall(r"CREATE\s+(?:OR\s+REPLACE\s+)?VIEW\s+(\w+)\s+AS", text):
        rows.append([f"`{view}`", "view", "projection"])
    rows.sort(key=lambda r: (r[1] != "table", r[0]))
    return rows


def render_route_map(root: Path = ROOT) -> str:
    sections = [
        ("# Codebase Route & Vertical-Slice Map", [
            MARKER,
            "",
            "Compact cross-reference index across PWA routes, stores, API wrappers, C# controllers, services, YAML workflows, and PostgreSQL schema objects. Refresh with `task agent:map`; verify with `task agent:map -- --check`.",
        ]),
        ("## 1. PWA App Routes (`pwa/src/app/**/page.tsx`)", format_table(["Route", "Page", "Direct Stores / Wrappers / Entry"], collect_pwa_routes(root))),
        ("## 2. PWA Zustand Stores (`pwa/src/store/*.ts`)", format_table(["Store File", "Exports", "API Wrappers"], collect_pwa_stores(root))),
        ("## 3. PWA API Client Wrappers (`pwa/src/lib/api/*.ts`)", format_table(["Wrapper", "Kiota Namespace / Transport"], collect_api_wrappers(root))),
        ("## 4. Backend Controllers (`api/src/RecipeApi/Controllers/*.cs`)", format_table(["Controller", "Route Prefix", "Endpoints", "Injected Services"], collect_controllers(root))),
        ("## 5. Backend Domain Service Groups", format_table(["Directory", "Units", "Representative Types"], collect_service_groups(root))),
        ("## 6. YAML Workflows (`api/src/RecipeApi/Workflows/*.yaml`)", format_table(["Workflow", "Parameters", "Processor Chain"], collect_workflows(root))),
        ("## 7. PostgreSQL Schema (`api/database/schema.sql`)", format_table(["Object", "Kind", "Foreign Keys / Role"], collect_sql_objects(root))),
    ]
    lines: list[str] = []
    for heading, body in sections:
        lines.append(heading)
        lines.append("")
        lines.extend(body)
        lines.append("")
    return "\n".join(lines)


def sync(root: Path = ROOT, check: bool = False) -> list[str]:
    target = root / OUTPUT_REL
    expected = render_route_map(root)
    current = target.read_text(encoding="utf-8") if target.is_file() else None
    if current == expected:
        return []
    problem = f"{OUTPUT_REL.as_posix()} is {'stale' if current is not None else 'missing'}"
    if not check:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(expected, encoding="utf-8")
    return [problem]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify docs/generated/route-map.md without writing.")
    args = parser.parse_args(argv)
    problems = sync(ROOT, check=args.check)
    if args.check:
        if problems:
            for item in problems:
                print(f"✗ {item}", file=sys.stderr)
            print("Run: task agent:map", file=sys.stderr)
            return 1
        print(f"✓ {OUTPUT_REL.as_posix()} is up to date")
        return 0
    print(f"✓ Generated {OUTPUT_REL.as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
