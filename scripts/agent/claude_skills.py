"""Generate Claude Code skill shims that point at the shared .agents/skills sources.

Claude Code discovers skills only under .claude/skills/. The canonical skills stay in
.agents/skills/ (read natively by Codex and Antigravity, with links relative to each
skill's folder). Each shim carries only the discovery frontmatter and routes Claude to
the canonical SKILL.md, so no host-specific copy or symlink is needed.

Usage: claude_skills.py [--check]
"""
import argparse
import shutil
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SOURCE_DIR = Path('.agents/skills')
SHIM_DIR = Path('.claude/skills')
MARKER = '<!-- Generated by `task agent:skills:claude` from {source}. Do not edit. -->'


def read_frontmatter(path):
    text = path.read_text(encoding='utf-8')
    if not text.startswith('---\n'):
        raise ValueError(f'{path}: missing frontmatter')
    end = text.find('\n---', 4)
    if end == -1:
        raise ValueError(f'{path}: unterminated frontmatter')
    data = yaml.safe_load(text[4:end]) or {}
    for key in ('name', 'description'):
        if not isinstance(data.get(key), str) or not data[key].strip():
            raise ValueError(f'{path}: frontmatter needs a non-empty {key!r}')
    return data


def render(name, description, folder):
    source = (SOURCE_DIR / folder / 'SKILL.md').as_posix()
    header = yaml.safe_dump({'name': name, 'description': description},
                            sort_keys=False, allow_unicode=True, width=10_000)
    return (
        f'---\n{header}---\n\n'
        f'{MARKER.format(source=source)}\n\n'
        f'Read `{source}` and follow it. Resolve its relative links from\n'
        f'`{(SOURCE_DIR / folder).as_posix()}/`, not from this file.\n'
    )


def expected_shims(root):
    shims = {}
    for skill in sorted((root / SOURCE_DIR).glob('*/SKILL.md')):
        folder = skill.parent.name
        meta = read_frontmatter(skill)
        name = meta['name'].strip()
        if name in shims:
            raise ValueError(f'duplicate skill name {name!r} in {skill}')
        shims[name] = render(name, meta['description'].strip(), folder)
    return shims


def is_generated(path):
    try:
        return '<!-- Generated by `task agent:skills:claude`' in path.read_text(encoding='utf-8')
    except OSError:
        return False


def sync(root, check):
    shim_root = root / SHIM_DIR
    problems = []
    if shim_root.is_symlink():
        problems.append(f'{SHIM_DIR} is a symlink; expected a directory of generated shims')
        if not check:
            shim_root.unlink()
    expected = expected_shims(root)

    for name, content in expected.items():
        target = shim_root / name / 'SKILL.md'
        current = target.read_text(encoding='utf-8') if target.is_file() else None
        if current == content:
            continue
        problems.append(f'{target.relative_to(root)} is {"stale" if current else "missing"}')
        if not check:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding='utf-8')

    if shim_root.is_dir() and not shim_root.is_symlink():
        for stale in sorted(shim_root.glob('*/SKILL.md')):
            if stale.parent.name in expected or not is_generated(stale):
                continue
            problems.append(f'{stale.relative_to(root)} has no source skill')
            if not check:
                shutil.rmtree(stale.parent)
    return problems


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true',
                        help='report drift without writing; exit 1 when shims are out of date')
    args = parser.parse_args(argv)
    problems = sync(ROOT, args.check)
    if args.check:
        for problem in problems:
            print(f'✗ {problem}', file=sys.stderr)
        if problems:
            print('Run: task agent:skills:claude', file=sys.stderr)
            return 1
        print('✓ Claude skill shims match .agents/skills')
        return 0
    for problem in problems:
        print(f'↻ {problem}')
    print(f'✓ {len(expected_shims(ROOT))} Claude skill shims in {SHIM_DIR}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
